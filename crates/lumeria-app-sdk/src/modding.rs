//! # Component Model Modding Extensions: D&D Rolls, Combat Events & Procedural Dungeons
//!
//! Standardizes on the official WebAssembly Component Model (wit-bindgen / WASI Preview 2)
//! exposing verified `.wit` interfaces for guest mods authored in Rust, TinyGo, or Zig.

use serde::{Deserialize, Serialize};

pub const LUMERIA_MOD_WIT: &str = include_str!("../wit/lumeria-mod.wit");

/// D&D Dice types supported by the WebAssembly component model hook.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DiceType {
    D4 = 4,
    D6 = 6,
    D8 = 8,
    D10 = 10,
    D12 = 12,
    D20 = 20,
    D100 = 100,
}

/// A request to evaluate a D&D roll hook.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RollRequest {
    pub dice: DiceType,
    pub count: u32,
    pub modifier: i32,
    pub advantage: bool,
    pub disadvantage: bool,
    pub reason: String,
}

/// The verified outcome of a D&D dice roll.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RollOutcome {
    pub total: i32,
    pub natural_rolls: Vec<u32>,
    pub modifier: i32,
    pub is_critical_success: bool,
    pub is_critical_failure: bool,
}

/// Damage types for combat events.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DamageType {
    Slashing,
    Piercing,
    Bludgeoning,
    Fire,
    Cold,
    Lightning,
    Radiant,
    Necrotic,
    Force,
}

/// Combatant state passed across the WASM guest boundary.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Combatant {
    pub id: u64,
    pub name: String,
    pub max_hp: f32,
    pub current_hp: f32,
    pub armor_class: u32,
    pub initiative: i32,
}

/// Attack intent dispatched to mod combat hooks.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AttackIntent {
    pub attacker_id: u64,
    pub target_id: u64,
    pub weapon_name: String,
    pub attack_bonus: i32,
    pub damage_dice: String,
    pub dmg_type: DamageType,
}

/// Result of resolving combat action through the component model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CombatResolution {
    pub hit: bool,
    pub critical: bool,
    pub damage_dealt: f32,
    pub target_downed: bool,
    pub combat_log: String,
}

/// Procedural dungeon themes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DungeonTheme {
    AbyssalTrench,
    ForgottenCitadel,
    CelestialSanctum,
    KarmanRuins,
    UndergroundVault,
}

/// A procedural dungeon room node.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DungeonRoom {
    pub room_id: u32,
    pub x: i32,
    pub y: i32,
    pub width: u32,
    pub height: u32,
    pub theme: DungeonTheme,
    pub has_treasure: bool,
    pub enemy_count: u32,
    pub corridor_connections: Vec<u32>,
}

/// A procedurally generated dungeon layout generated by guest component mod.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DungeonLayout {
    pub seed: u64,
    pub level: u32,
    pub rooms: Vec<DungeonRoom>,
    pub boss_room_id: u32,
}

/// Host evaluation engine executing D&D dice rolls and procedural generation contracts.
#[derive(Default, Debug, Clone)]
pub struct LumeriaModHostEngine;

impl LumeriaModHostEngine {
    pub fn new() -> Self {
        Self
    }

    /// Evaluates a D&D roll request using a pseudo-random seed.
    pub fn execute_dice_roll(&self, req: &RollRequest, seed: u64) -> RollOutcome {
        let sides = req.dice as u32;
        let mut natural_rolls = Vec::new();
        let mut rng = seed;

        let roll_count = if req.advantage || req.disadvantage {
            req.count.max(1) * 2
        } else {
            req.count.max(1)
        };

        for _ in 0..roll_count {
            rng = rng.wrapping_mul(6364136223846793005).wrapping_add(1);
            let roll = ((rng >> 32) as u32 % sides) + 1;
            natural_rolls.push(roll);
        }

        let chosen_natural = if req.advantage {
            *natural_rolls.iter().max().unwrap_or(&1)
        } else if req.disadvantage {
            *natural_rolls.iter().min().unwrap_or(&1)
        } else {
            natural_rolls.iter().sum::<u32>()
        };

        let is_critical_success = req.dice == DiceType::D20 && natural_rolls.contains(&20);
        let is_critical_failure = req.dice == DiceType::D20 && natural_rolls.contains(&1);

        RollOutcome {
            total: (chosen_natural as i32) + req.modifier,
            natural_rolls,
            modifier: req.modifier,
            is_critical_success,
            is_critical_failure,
        }
    }

    /// Resolves an attack hook against target combatant stats.
    pub fn resolve_attack(
        &self,
        intent: &AttackIntent,
        target: &Combatant,
        d20_roll: u32,
    ) -> CombatResolution {
        let is_critical = d20_roll == 20;
        let hit = is_critical || ((d20_roll as i32 + intent.attack_bonus) >= target.armor_class as i32);

        let damage = if hit {
            let base_dmg = 8.0f32;
            if is_critical { base_dmg * 2.0 } else { base_dmg }
        } else {
            0.0
        };

        let remaining_hp = target.current_hp - damage;
        let target_downed = remaining_hp <= 0.0;

        let log = format!(
            "{} attacked {} with {} (Roll: {}, Bonus: {} vs AC: {}) -> {}. Dealt {:.1} {:?} damage.",
            intent.attacker_id,
            target.name,
            intent.weapon_name,
            d20_roll,
            intent.attack_bonus,
            target.armor_class,
            if hit { "HIT" } else { "MISS" },
            damage,
            intent.dmg_type,
        );

        CombatResolution {
            hit,
            critical: is_critical,
            damage_dealt: damage,
            target_downed,
            combat_log: log,
        }
    }

    /// Procedural dungeon layout synthesis adhering to `lumeria:modding/procedural-dungeon`.
    pub fn generate_procedural_dungeon(
        &self,
        seed: u64,
        floor_level: u32,
        theme: DungeonTheme,
    ) -> DungeonLayout {
        let room_count = (4 + (floor_level * 2)).min(12);
        let mut rooms = Vec::with_capacity(room_count as usize);

        for i in 0..room_count {
            let connections = if i > 0 { vec![i - 1] } else { vec![1] };
            rooms.push(DungeonRoom {
                room_id: i,
                x: (i as i32 * 12) - 30,
                y: ((seed.wrapping_add(i as u64) % 5) as i32 * 8) - 16,
                width: 8 + ((seed.wrapping_add(i as u64) % 6) as u32),
                height: 8 + ((seed.wrapping_add(i as u64 * 3) % 6) as u32),
                theme,
                has_treasure: i % 3 == 0,
                enemy_count: (i % 4) + 1,
                corridor_connections: connections,
            });
        }

        DungeonLayout {
            seed,
            level: floor_level,
            rooms,
            boss_room_id: room_count - 1,
        }
    }
}
